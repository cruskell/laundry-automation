#!/usr/bin/env python3
"""Generate the Rust API client from spec/openapi.yaml; --check detects drift."""
import argparse
import hashlib
import json
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]

def quote(value):
    return json.dumps(value, ensure_ascii=False)

def generate():
    raw = (ROOT / 'spec/openapi.yaml').read_bytes()
    spec = yaml.safe_load(raw)
    aliases = []
    for path, item in spec['paths'].items():
        for method, operation in item.items():
            for alias in operation.get('x-cli-operations', []):
                params = item.get('parameters', []) + operation.get('parameters', []) + alias.get('extra_params', [])
                params = [p for p in params if p['name'] != 'X-ApplianceId']
                if 'only_params' in alias:
                    params = [p for p in params if p['name'] in alias['only_params']]
                aliases.append((path, method, operation, alias, params))
    lines = ['// @generated by scripts/generate-api-client.py; DO NOT EDIT.',
             '// Schema SHA-256: ' + hashlib.sha256(raw).hexdigest(),
             'use clap::ValueEnum;', 'use reqwest::Method;',
             'use serde_json::Value;', '#[derive(Clone, Copy, Debug, ValueEnum)]', 'pub enum Operation {']
    for _, _, _, a, _ in aliases:
        lines += [f'    #[value(name = {quote(a["name"])})]', f'    {a["variant"]},']
    lines += ['}', 'pub struct Endpoint {', '    pub method: Method,', "    pub path: &'static str,", '    pub appliance: bool,', "    pub required: &'static [&'static str],", "    pub optional: &'static [&'static str],", '    pub body: bool,', "    pub headers: &'static [(&'static str, &'static str)],", '}', 'impl Operation {', '    pub fn endpoint(self) -> Endpoint {', '        match self {']
    for path, method, op, a, params in aliases:
        name = lambda p: p.get('x-cli-name', p['name'])
        req = [name(p) for p in params if p.get('required')]
        opt = [name(p) for p in params if not p.get('required')]
        headers = [(name(p), p['name']) for p in params if p['in'] == 'header']
        appliance = a.get('appliance', False) or any(p['name'] == 'X-ApplianceId' and p.get('required') for p in op.get('parameters', []))
        body = 'requestBody' in op and 'generated_body' not in a
        arr = lambda xs: '&[' + ', '.join(quote(x) for x in xs) + ']'
        hs = '&[' + ', '.join('('+quote(k)+', '+quote(v)+')' for k,v in headers) + ']'
        lines += [f'            Self::{a["variant"]} => Endpoint {{ method: Method::{method.upper()}, path: {quote(path.removeprefix("/laundry/v5/"))}, appliance: {str(appliance).lower()}, required: {arr(req)}, optional: {arr(opt)}, body: {str(body).lower()}, headers: {hs} }},']
    lines += ['        }', '    }', '    pub fn name(self) -> String {', '        self.to_possible_value().expect("visible operation").get_name().to_owned()', '    }', '    pub fn generated_body(self, appliance: Option<&str>) -> Option<Value> {', '        let mut body: Value = match self {']
    for _,_,_,a,_ in aliases:
        if 'generated_body' in a:
            lines += [f'            Self::{a["variant"]} => serde_json::from_str({quote(json.dumps(a["generated_body"], separators=(",", ":")))}).expect("generated JSON"),']
    lines += ['            _ => return None,', '        };', '        fn substitute(value: &mut Value, appliance: Option<&str>) {', '            match value {', '                Value::String(s) if s == "$appliance_id" => *s = appliance.expect("validated appliance").to_owned(),', '                Value::Array(items) => items.iter_mut().for_each(|v| substitute(v, appliance)),', '                Value::Object(fields) => fields.values_mut().for_each(|v| substitute(v, appliance)),', '                _ => {}', '            }', '        }', '        substitute(&mut body, appliance);', '        Some(body)', '    }', '}']
    # The transport template lives here; endpoint contracts above come exclusively from OpenAPI.
    lines += ['impl Operation {', '    pub fn validate_request(self, body: &Value) -> anyhow::Result<()> {', '        let schema = match self {']
    for _, _, op, a, _ in aliases:
        if 'requestBody' in op:
            schema = a.get('request_schema') or op['requestBody']['content']['application/json']['schema']['$ref'].rsplit('/', 1)[1]
            lines += [f'            Self::{a["variant"]} => {quote(schema)},']
    lines += ['            _ => return Ok(()),', '        };', '        crate::schema_validation::validate(schema, body)', '    }', '}']
    lines += [TRANSPORT]
    return '\n'.join(lines) + '\n'

TRANSPORT = '''pub fn send(
    client: &reqwest::blocking::Client,
    method: Method,
    url: url::Url,
    body: Option<&Value>,
    headers: &std::collections::BTreeMap<String, String>,
    token: Option<&str>,
    appliance: Option<&str>,
) -> anyhow::Result<(u16, Value)> {
    let timestamp = chrono::Utc::now()
        .with_timezone(&chrono::FixedOffset::east_opt(9 * 3600).unwrap())
        .format("%Y%m%d%H%M%S%z").to_string();
    let mut request = client.request(method, url)
        .header("Accept", "application/json")
        .header("Content-Language", "ja_JP")
        .header("X-Timestamp", timestamp);
    if let Some(token) = token {
        request = request.bearer_auth(token).header("Cookie", format!("atkn={token}"));
    }
    if let Some(id) = appliance { request = request.header("X-ApplianceId", id); }
    for (name, value) in headers { request = request.header(name, value); }
    if let Some(body) = body { request = request.json(body); }
    let response = request.send()?;
    let code = response.status().as_u16();
    let text = response.text()?;
    let data = if text.trim().is_empty() { Value::Null } else {
        serde_json::from_str(&text).unwrap_or_else(|_| serde_json::json!({"non_json_response":text}))
    };
    Ok((code, data))
}'''

if __name__ == '__main__':
    import subprocess
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'], input=generate(), text=True, capture_output=True, check=True).stdout
    output = ROOT / 'src/generated_api.rs'
    schema_output = ROOT / 'src/generated_api_schemas.json'
    schemas = json.dumps(yaml.safe_load((ROOT / 'spec/openapi.yaml').read_text())['components']['schemas'], ensure_ascii=False, indent=2) + '\n'
    if args.check:
        if not output.exists() or output.read_text() != generated or not schema_output.exists() or schema_output.read_text() != schemas:
            raise SystemExit('Generated client is stale; run python3 scripts/generate-api-client.py')
    else:
        output.write_text(generated)
        schema_output.write_text(schemas)
